-- Fresh Neon project only. Apply after enabling Managed Better Auth and Data API.
-- This migration never imports or deletes Supabase data.
begin;

create extension if not exists btree_gist;

create table public.barbearias (
  id uuid primary key default gen_random_uuid(),
  proprietario_id uuid not null unique,
  nome text not null check (length(trim(nome)) between 2 and 120),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  telefone text,
  descricao text,
  logo_url text,
  capa_url text,
  instagram text,
  endereco text,
  ativa boolean not null default true,
  horario_abertura time not null default time '08:00',
  horario_fechamento time not null default time '21:00',
  dia_folga smallint not null default 0 check (dia_folga between 0 and 6),
  horarios_funcionamento jsonb not null default '[{"aberto":true,"abertura":"08:00","fechamento":"21:00"},{"aberto":true,"abertura":"08:00","fechamento":"21:00"},{"aberto":true,"abertura":"08:00","fechamento":"21:00"},{"aberto":true,"abertura":"08:00","fechamento":"21:00"},{"aberto":true,"abertura":"08:00","fechamento":"21:00"},{"aberto":true,"abertura":"08:00","fechamento":"21:00"},{"aberto":true,"abertura":"08:00","fechamento":"21:00"}]'::jsonb,
  created_at timestamptz not null default now(),
  check (horario_abertura < horario_fechamento),
  check (jsonb_typeof(horarios_funcionamento) = 'array' and jsonb_array_length(horarios_funcionamento) = 7)
);

create table public.servicos (
  id bigint generated by default as identity primary key,
  barbearia_id uuid not null references public.barbearias(id) on delete cascade,
  nome text not null check (length(trim(nome)) between 1 and 120),
  descricao text,
  preco numeric(10,2) not null check (preco > 0),
  duracao integer not null check (duracao between 1 and 1440),
  ativo boolean not null default true,
  excluido_em timestamptz,
  created_at timestamptz not null default now(),
  unique (id, barbearia_id)
);

create table public.barbeiros (
  id uuid primary key default gen_random_uuid(),
  barbearia_id uuid not null references public.barbearias(id) on delete cascade,
  nome text not null check (length(trim(nome)) between 1 and 120),
  ativo boolean not null default true,
  horario_abertura time not null default time '08:00',
  horario_fechamento time not null default time '21:00',
  dia_folga smallint not null default 0 check (dia_folga between 0 and 6),
  created_at timestamptz not null default now(),
  unique (id, barbearia_id),
  check (horario_abertura < horario_fechamento)
);

create table public.profiles (
  id uuid primary key,
  nome text,
  telefone text,
  avatar_url text,
  barbearias_favoritas jsonb not null default '[]'::jsonb
    check (jsonb_typeof(barbearias_favoritas) = 'array'),
  created_at timestamptz not null default now()
);

create table public.agendamentos (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null,
  barbearia_id uuid not null references public.barbearias(id),
  servico_id bigint references public.servicos(id) on delete set null,
  barbeiro_id uuid,
  data date not null,
  horario time not null,
  status text not null default 'confirmado' check (status in ('confirmado','pendente','aguardando','concluido','cancelado')),
  servico_nome text,
  servico_descricao text,
  servico_preco numeric(10,2),
  servico_duracao integer,
  created_at timestamptz not null default now(),
  constraint agendamento_barbeiro_da_barbearia foreign key (barbeiro_id, barbearia_id)
    references public.barbeiros(id, barbearia_id),
  check (status = 'cancelado' or servico_duracao > 0),
  constraint agendamento_barbeiro_sem_sobreposicao exclude using gist (
    barbeiro_id with =,
    tsrange(data + horario, data + horario + servico_duracao * interval '1 minute', '[)') with &&
  ) where (barbeiro_id is not null and status <> 'cancelado'),
  constraint agendamento_sem_barbeiro_sem_sobreposicao exclude using gist (
    barbearia_id with =,
    tsrange(data + horario, data + horario + servico_duracao * interval '1 minute', '[)') with &&
  ) where (barbeiro_id is null and status <> 'cancelado')
);

create index agendamentos_por_barbearia on public.agendamentos(barbearia_id, data, horario);
create index agendamentos_por_cliente on public.agendamentos(usuario_id, data desc);

create table public.notificacoes_barbeiro (
  id uuid primary key default gen_random_uuid(),
  barbearia_id uuid not null references public.barbearias(id) on delete cascade,
  agendamento_id bigint references public.agendamentos(id) on delete set null,
  titulo text not null default 'Novo agendamento',
  mensagem text not null,
  lida_em timestamptz,
  created_at timestamptz not null default now()
);
create index notificacoes_barbeiro_historico on public.notificacoes_barbeiro(barbearia_id, created_at desc);

-- Private upload quota. The web server uses the database owner connection,
-- never a Data API browser token, to claim a slot.
create schema naregua_private;
create table naregua_private.upload_quota (
  user_id uuid not null,
  window_start timestamptz not null,
  used integer not null check (used between 1 and 10),
  primary key (user_id, window_start)
);
revoke all on schema naregua_private from public, anonymous, authenticated;
revoke all on naregua_private.upload_quota from public, anonymous, authenticated;

commit;
